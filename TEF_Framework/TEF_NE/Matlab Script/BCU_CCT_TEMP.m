% Pre-allocate vectors
gij_pre = zeros(n_edge,1); bij_pre = zeros(n_edge,1);
gij_flt = zeros(n_edge,1); bij_flt = zeros(n_edge,1);
gij_pst = zeros(n_edge,1); bij_pst = zeros(n_edge,1);

