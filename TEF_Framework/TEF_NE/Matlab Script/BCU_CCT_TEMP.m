%% ----------------- HELPER: ROBUST NR SOLVER -----------------
function [x, converged] = Robust_NR(Fun, Jac, x0)
    x = x0;
    converged = false;
    max_iter = 50;
    tol = 1e-6;
    lambda = 1.0; % Damping factor
    
    for i = 1:max_iter
        F = Fun(x);
        err = norm(F, inf);
        if err < tol
            converged = true;
            return;
        end
        
        J = Jac(x);
        
        % Check for singular matrix
        if rcond(J) < 1e-12
            dx = pinv(J) * -F; % Use pseudo-inverse if singular
        else
            dx = J \ -F;
        end
        
        % Simple Damping line search check
        x_new = x + lambda * dx;
        if norm(Fun(x_new), inf) > err
             % If error increases, reduce step
             x_new = x + 0.5 * lambda * dx;
        end
        x = x_new;
    end
    
    % Final check
    if norm(Fun(x), inf) < 1e-3 % Relaxed tolerance for final check
        converged = true;
    end
end