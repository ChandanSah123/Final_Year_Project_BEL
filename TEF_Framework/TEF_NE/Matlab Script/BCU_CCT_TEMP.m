    [ zeros(num_gen), eye(num_gen) - ones(num_gen,1)*M_gen'/M_T; ...
      (1./M_gen) .* ( ...
         - E_kron' * diag(bij_k .* cos(E_kron * x(idx_delta))) * E_kron ...
